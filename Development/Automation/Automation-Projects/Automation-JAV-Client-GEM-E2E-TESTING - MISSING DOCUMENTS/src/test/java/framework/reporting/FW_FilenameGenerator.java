import framework.http.FW_Http;
import framework.advisor.FW_AdvisorAudience;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

/**
 * Utility for generating standardized report filenames.
 * 
 * <p>Produces consistent, descriptive filenames following the established pattern:
 * <br>{@code Audit_HttpReview_{domain}_{date}_{time}_{Audience-Depth}.md}
 * 
 * <p><b>Examples:</b>
 * <ul>
 *   <li>Executive summary: {@code Audit_HttpReview_example-com_2025-11-07_14-30-25_Executive-Summary.md}</li>
 *   <li>Developer report: {@code Audit_HttpReview_example-com_2025-11-07_14-30-25_Developer-Standard.md}</li>
 *   <li>Security analysis: {@code Audit_HttpReview_example-com_2025-11-07_14-30-25_Security-Comprehensive.md}</li>
 * </ul>
 * 
 * <p><b>Thread Safety:</b> This class is stateless and thread-safe.
 * 
 * @since 1.0.0
 * @see framework.reporting.FW_ReportContext
 */
public class FW_FilenameGenerator {
    
    private static final DateTimeFormatter TIMESTAMP_FORMATTER = 
        DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss");
    
    // Private constructor - utility class
    private FW_FilenameGenerator() {
        throw new UnsupportedOperationException("Utility class cannot be instantiated");
    }
    
    /**
     * Generates standardized report filename from HTTP data and context.
     * 
     * <p>Format: {@code Audit_HttpReview_{domain}_{date}_{time}_{Audience-Depth}.md}
     * 
     * @param httpData HTTP transaction data (for URL/domain extraction)
     * @param context Report context (for audience and depth)
     * @return Formatted filename string
     * @throws IllegalArgumentException if httpData or context is null
     * 
     * @example
     * FW_Http http = ...; // URL: https://www.example.com
     * FW_ReportContext ctx = FW_ReportContext.builder()
     *     .withDepth(ReportDepth.STANDARD)
     *     .withAudience(FW_AdvisorAudience.DEVELOPER)
     *     .build();
     * String filename = FW_FilenameGenerator.generate(http, ctx);
     * // Result: "Audit_HttpReview_www-example-com_2025-11-07_14-30-25_Developer-Standard.md"
     */
    public static String generate(FW_Http httpData, FW_ReportContext context) {
        if (httpData == null) {
            throw new IllegalArgumentException("HTTP data cannot be null");
        }
        if (context == null) {
            throw new IllegalArgumentException("Report context cannot be null");
        }
        
        String domain = extractDomain(httpData.getRequestUrl());
        
        // Get timestamp and split into date and time components
        LocalDateTime now = LocalDateTime.now();
        String timestamp = now.format(TIMESTAMP_FORMATTER);
        String[] parts = timestamp.split("T");
        String date = parts[0]; // "2025-11-07"
        String time = parts[1].replace(":", "-"); // "14-30-25"
        
        // Generate suffix based on audience and depth
        String suffix = generateSuffix(context.getAudience(), context.getDepth());
        
        return String.format("Audit_HttpReview_%s_%s_%s_%s.md", domain, date, time, suffix);
    }
    
    /**
     * Generates human-readable suffix for filename based on audience and depth.
     * 
     * <p>Special case: EXECUTIVE audience + SUMMARY depth = "Executive-Summary"
     * <br>Default pattern: "{Audience}-{Depth}" with proper capitalization
     * 
     * @param audience Target audience enum
     * @param depth Report depth enum
     * @return Formatted suffix string
     * 
     * @example
     * generateSuffix(EXECUTIVE, SUMMARY) → "Executive-Summary"
     * generateSuffix(DEVELOPER, STANDARD) → "Developer-Standard"
     * generateSuffix(SECURITY_ENGINEER, COMPREHENSIVE) → "Security-Comprehensive"
     */
    private static String generateSuffix(FW_AdvisorAudience audience, FW_ReportDepth depth) {
        // Special case: Executive Summary
        if (audience == FW_AdvisorAudience.EXECUTIVE && depth == FW_ReportDepth.SUMMARY) {
            return "Executive-Summary";
        }
        
        // Convert audience name to proper case
        String audienceName = formatAudienceName(audience.name());
        
        // Convert depth to proper case
        String depthName = formatDepthName(depth.name());
        
        return audienceName + "-" + depthName;
    }
    
    /**
     * Formats audience enum name to human-readable form.
     * 
     * @param audienceName Raw enum name (e.g., "SECURITY_ENGINEER")
     * @return Formatted name (e.g., "Security")
     */
    private static String formatAudienceName(String audienceName) {
        switch (audienceName) {
            case "SECURITY_ENGINEER":
                return "Security";
            case "OPS_INFRASTRUCTURE":
                return "Ops";
            case "QA_TESTER":
                return "QA";
            case "PROJECT_MANAGER":
                return "PM";
            case "DEVELOPER":
                return "Developer";
            case "EXECUTIVE":
                return "Executive";
            default:
                // Fallback: capitalize first letter
                return audienceName.substring(0, 1).toUpperCase() + 
                       audienceName.substring(1).toLowerCase();
        }
    }
    
    /**
     * Formats depth enum name to human-readable form.
     * 
     * @param depthName Raw enum name (e.g., "COMPREHENSIVE")
     * @return Formatted name (e.g., "Comprehensive")
     */
    private static String formatDepthName(String depthName) {
        // Simple capitalize first letter, rest lowercase
        return depthName.substring(0, 1).toUpperCase() + 
               depthName.substring(1).toLowerCase();
    }
    
    /**
     * Extracts clean domain name from URL for use in filenames.
     * 
     * <p>Removes protocol, path, port, and query parameters.
     * Preserves subdomains (including www) and converts dots to dashes.
     * 
     * @param url Full URL string
     * @return Clean domain name safe for filenames
     * 
     * @example
     * extractDomain("https://www.example.com:8080/path?query=value") → "www-example-com"
     * extractDomain("http://subdomain.example.com/") → "subdomain-example-com"
     * extractDomain("https://saucedemo.com/") → "saucedemo-com"
     */
    private static String extractDomain(String url) {
        if (url == null || url.isEmpty()) {
            return "unknown";
        }
        
        try {
            // Remove protocol (http:// or https://) but KEEP www
            String domain = url.replaceFirst("^https?://", "");
            
            // Remove path (everything after first /)
            domain = domain.replaceFirst("/.*$", "");
            
            // Remove port (everything after :)
            domain = domain.replaceFirst(":.*$", "");
            
            // Replace dots with dashes for filename safety
            domain = domain.replace(".", "-");
            
            // Clean any remaining invalid characters
            domain = domain.replaceAll("[^a-zA-Z0-9-]", "_");
            
            return domain.isEmpty() ? "unknown" : domain.toLowerCase();
            
        } catch (Exception e) {
            return "unknown";
        }
    }
    
    /**
     * Returns string representation of this utility class.
     * 
     * @return Class description
     */
    @Override
    public String toString() {
        return "FW_FilenameGenerator[utility class for report filename generation]";
    }
}