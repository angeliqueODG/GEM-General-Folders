import framework.advisor.FW_AdvisorAudience;

/**
 * Immutable configuration context for report generation.
 * 
 * <p>Encapsulates all configuration needed during report rendering including
 * depth level, target audience, and output filename. This context object is
 * passed to topics during rendering to provide consistent configuration
 * throughout the report generation process.
 * 
 * <p><b>Immutability:</b>
 * <br>Once constructed, a FW_ReportContext cannot be modified. This ensures
 * thread safety and prevents accidental configuration changes during report
 * generation. To create a new context with different settings, use the
 * builder pattern.
 * 
 * <p><b>Builder Pattern:</b>
 * <br>Use the fluent builder API for clean, readable construction:
 * <pre>
 * FW_ReportContext context = FW_ReportContext.builder()
 *     .withDepth(ReportDepth.STANDARD)
 *     .withAudience(FW_AdvisorAudience.DEVELOPER)
 *     .withFilename("http-audit-report.md")
 *     .build();
 * </pre>
 * 
 * <p><b>Usage in Topics:</b>
 * <pre>
 * public String render(FW_Http data, FW_ReportContext context) {
 *     // Use depth to adjust detail level
 *     if (context.getDepth().includesTechnicalDetails()) {
 *         // Include technical information
 *     }
 *     
 *     // Get audience-specific recommendations
 *     List&lt;FW_AdvisorRecommendation&gt; recs = FW_Advisor.getRecommendations(
 *         data,
 *         context.getAudience(),
 *         getFindingType()
 *     );
 *     
 *     return renderedContent;
 * }
 * </pre>
 * 
 * <p><b>Thread Safety:</b>
 * <br>This class is immutable and thread-safe. A single context instance can
 * be safely shared across multiple threads during concurrent report generation.
 * 
 * @since 1.0.0
 * @see framework.reporting.ReportDepth
 * @see framework.advisor.FW_AdvisorAudience
 * @see framework.reporting.FW_ReportTopic
 */
